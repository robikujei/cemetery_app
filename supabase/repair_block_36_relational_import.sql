-- Promote the reviewed Block 36 register into the application's actual records.
-- Prerequisite: the reviewed register-only import (678 unique matched lots).
-- Run with an administrative database connection. Re-running is idempotent.
-- Test first by replacing the final COMMIT with ROLLBACK.
BEGIN;
SET LOCAL lock_timeout = '10s';
LOCK TABLE public.cemetery_lot, public.lot_register_details, public.users,
  public.lot_ownership, public.burial_record IN SHARE ROW EXCLUSIVE MODE;

CREATE SCHEMA IF NOT EXISTS private_lot_import;
REVOKE ALL ON SCHEMA private_lot_import FROM PUBLIC, anon, authenticated;
CREATE TABLE IF NOT EXISTS private_lot_import.relational_backup (
  run_id timestamptz NOT NULL, table_name text NOT NULL, row_key text NOT NULL,
  row_data jsonb NOT NULL, PRIMARY KEY(run_id, table_name, row_key)
);

-- Historical profiles have no login credentials. Do not create auth.users rows,
-- fabricated email addresses, passwords, death dates, or payment history.
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS register_import_key text;
ALTER TABLE public.burial_record ADD COLUMN IF NOT EXISTS register_import_key text;
ALTER TABLE public.lot_ownership ADD COLUMN IF NOT EXISTS register_import_key text;
ALTER TABLE public.lot_ownership ADD COLUMN IF NOT EXISTS purchase_note text;
CREATE UNIQUE INDEX IF NOT EXISTS users_register_import_key ON public.users(register_import_key);
CREATE UNIQUE INDEX IF NOT EXISTS burial_register_import_key ON public.burial_record(register_import_key);
CREATE UNIQUE INDEX IF NOT EXISTS ownership_register_import_key ON public.lot_ownership(register_import_key);
ALTER TABLE public.users ALTER COLUMN email DROP NOT NULL, ALTER COLUMN password DROP NOT NULL;
ALTER TABLE public.burial_record ALTER COLUMN death_date DROP NOT NULL;
ALTER TABLE public.lot_ownership ALTER COLUMN start_date DROP NOT NULL, ALTER COLUMN total_months DROP NOT NULL;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.users'::regclass AND conname='users_registered_credentials') THEN
    ALTER TABLE public.users ADD CONSTRAINT users_registered_credentials CHECK
      ((email IS NOT NULL AND password IS NOT NULL) OR (register_import_key IS NOT NULL AND role='lot_owner'));
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.burial_record'::regclass AND conname='burial_registered_death_date') THEN
    ALTER TABLE public.burial_record ADD CONSTRAINT burial_registered_death_date CHECK
      (death_date IS NOT NULL OR register_import_key IS NOT NULL);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid='public.lot_ownership'::regclass AND conname='ownership_registered_terms') THEN
    ALTER TABLE public.lot_ownership ADD CONSTRAINT ownership_registered_terms CHECK
      ((start_date IS NOT NULL AND total_months IS NOT NULL) OR register_import_key IS NOT NULL);
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.graves (
  grave_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lot_id integer NOT NULL REFERENCES public.cemetery_lot(lot_id) ON DELETE CASCADE,
  grave_label text NOT NULL,
  status text NOT NULL DEFAULT 'Available' CHECK(status IN ('Available','Reserved','Occupied')),
  burial_id integer REFERENCES public.burial_record(burial_id) ON DELETE SET NULL,
  notes text, created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(), UNIQUE(lot_id,grave_label)
);
CREATE INDEX IF NOT EXISTS graves_lot_id_idx ON public.graves(lot_id);
CREATE INDEX IF NOT EXISTS graves_burial_id_idx ON public.graves(burial_id);
ALTER TABLE public.graves ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON public.graves TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON public.graves TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.graves_grave_id_seq TO authenticated;
DROP POLICY IF EXISTS graves_read ON public.graves;
CREATE POLICY graves_read ON public.graves FOR SELECT TO anon, authenticated USING(true);
DROP POLICY IF EXISTS graves_admin_write ON public.graves;
CREATE POLICY graves_admin_write ON public.graves FOR ALL TO authenticated
  USING(public.paper_user_role()='admin') WITH CHECK(public.paper_user_role()='admin');

CREATE TEMP TABLE source36 ON COMMIT DROP AS
SELECT l.lot_id, l.lot_number, l.lot_class_type, d.details,
  nullif(trim(regexp_replace(d.details->>'owner_name', '\s*\([0-9 -]+\)\s*$', '')), '') AS owner_name
FROM public.lot_register_details d JOIN public.cemetery_lot l USING(lot_id)
WHERE trim(l.block_number)='36';
DO $$ BEGIN
  IF (SELECT count(*) FROM source36)<>678 THEN
    RAISE EXCEPTION 'Expected the 678 reviewed Block 36 register entries; inspect source before importing';
  END IF;
  IF EXISTS(SELECT 1 FROM source36 GROUP BY ltrim(trim(lot_number),'0') HAVING count(*)>1) THEN
    RAISE EXCEPTION 'Duplicate Block 36 lot numbers';
  END IF;
END $$;

-- Preserve existing rows before any data updates; backup stays outside the API.
INSERT INTO private_lot_import.relational_backup
SELECT transaction_timestamp(),'cemetery_lot',l.lot_id::text,to_jsonb(l)
FROM public.cemetery_lot l JOIN source36 s USING(lot_id)
UNION ALL SELECT transaction_timestamp(),'lot_register_details',d.lot_id::text,to_jsonb(d)
FROM public.lot_register_details d JOIN source36 s USING(lot_id)
UNION ALL SELECT transaction_timestamp(),'lot_ownership',o.ownership_id::text,to_jsonb(o)
FROM public.lot_ownership o JOIN source36 s USING(lot_id)
UNION ALL SELECT transaction_timestamp(),'burial_record',b.burial_id::text,to_jsonb(b)
FROM public.burial_record b JOIN source36 s USING(lot_id)
UNION ALL SELECT transaction_timestamp(),'graves',g.grave_id::text,to_jsonb(g)
FROM public.graves g JOIN source36 s USING(lot_id);

CREATE TEMP TABLE owners36 ON COMMIT DROP AS
SELECT upper(owner_name) AS owner_key, min(owner_name) AS owner_name,
  'block36:owner:'||md5(upper(owner_name)) AS import_key,
  count(*)::integer AS number_of_lots,
  string_agg(lot_number, ', ' ORDER BY lot_number) AS lot_numbers
FROM source36 WHERE owner_name IS NOT NULL GROUP BY upper(owner_name);
ALTER TABLE owners36 ADD COLUMN mapped_user_id uuid;
-- Reuse a profile only when an existing ownership of the same source lot
-- corroborates the name (punctuation and case differences are harmless).
DO $$ BEGIN
  IF EXISTS(SELECT 1 FROM owners36 r JOIN source36 s ON upper(s.owner_name)=r.owner_key
    JOIN public.lot_ownership o USING(lot_id) JOIN public.users u USING(user_id)
    WHERE regexp_replace(upper(u.name),'[^A-Z0-9]','','g')=regexp_replace(r.owner_key,'[^A-Z0-9]','','g')
    GROUP BY r.owner_key HAVING count(DISTINCT u.user_id)>1) THEN
    RAISE EXCEPTION 'Multiple existing identities for a register owner';
  END IF;
END $$;
UPDATE owners36 r SET mapped_user_id=u.user_id
FROM source36 s JOIN public.lot_ownership o USING(lot_id) JOIN public.users u USING(user_id)
WHERE upper(s.owner_name)=r.owner_key
AND regexp_replace(upper(u.name),'[^A-Z0-9]','','g')=regexp_replace(r.owner_key,'[^A-Z0-9]','','g');
-- Name-only matches to existing accounts require human review, not guessing.
DO $$ BEGIN
  IF EXISTS(SELECT 1 FROM owners36 s JOIN public.users u ON upper(trim(u.name))=s.owner_key
    WHERE u.register_import_key IS DISTINCT FROM s.import_key AND u.user_id IS DISTINCT FROM s.mapped_user_id) THEN
    RAISE EXCEPTION 'An existing owner account matches a register name; resolve identity before importing';
  END IF;
END $$;
INSERT INTO public.users(name,role,register_import_key,block_number,lot_number,number_of_lots)
SELECT owner_name,'lot_owner',import_key,'36',lot_numbers,number_of_lots FROM owners36 WHERE mapped_user_id IS NULL
ON CONFLICT(register_import_key) DO NOTHING;
UPDATE owners36 o SET mapped_user_id=u.user_id FROM public.users u
WHERE o.mapped_user_id IS NULL AND u.register_import_key=o.import_key;

DO $$ BEGIN
  IF EXISTS(SELECT 1 FROM source36 s JOIN public.lot_ownership o USING(lot_id)
    JOIN owners36 r ON r.owner_key=upper(s.owner_name)
    WHERE o.user_id IS DISTINCT FROM r.mapped_user_id) THEN
    RAISE EXCEPTION 'A source lot already has ownership; resolve it before importing';
  END IF;
END $$;
INSERT INTO public.lot_ownership(lot_id,user_id,start_date,total_months,months_paid,status,purchase_note,register_import_key)
SELECT s.lot_id,o.mapped_user_id,(s.details->>'purchase_date')::date,NULL,NULL,NULL,
  s.details->>'purchase_note','block36:ownership:'||s.lot_id
FROM source36 s JOIN owners36 o ON o.owner_key=upper(s.owner_name)
ON CONFLICT(lot_id) DO NOTHING;

-- Each slash/newline separated deceased entry is one burial; keep annotations
-- verbatim in the name instead of silently discarding the source information.
CREATE TEMP TABLE deceased36 ON COMMIT DROP AS
SELECT DISTINCT s.lot_id,s.lot_number,s.owner_name,s.lot_class_type,trim(n.name) AS name,
  'block36:burial:'||s.lot_id||':'||md5(upper(trim(n.name))) AS import_key
FROM source36 s CROSS JOIN LATERAL regexp_split_to_table(s.details->>'deceased_names', E'[/\n\r]+') n(name)
WHERE nullif(trim(n.name),'') IS NOT NULL;
ALTER TABLE deceased36 ADD COLUMN mapped_burial_id integer;
DO $$ BEGIN
  IF EXISTS(SELECT 1 FROM deceased36 WHERE length(name)>100) THEN
    RAISE EXCEPTION 'A deceased name exceeds the schema length; inspect the source';
  END IF;
  IF EXISTS(SELECT 1 FROM deceased36 s JOIN public.burial_record b
    ON b.lot_id=s.lot_id AND upper(trim(b.name_of_deceased))=upper(s.name)
    GROUP BY s.import_key HAVING count(*)>1) THEN
    RAISE EXCEPTION 'Multiple existing burials match one source entry';
  END IF;
END $$;
UPDATE deceased36 s SET mapped_burial_id=b.burial_id FROM public.burial_record b
WHERE b.lot_id=s.lot_id AND upper(trim(b.name_of_deceased))=upper(s.name);
INSERT INTO public.burial_record(name_of_deceased,lot_id,registered_lot_owner,
  lot_location_no,burial_category,interment_total,register_import_key)
SELECT name,lot_id,owner_name,'36-'||lot_number,lot_class_type,NULL,import_key FROM deceased36 WHERE mapped_burial_id IS NULL
ON CONFLICT(register_import_key) DO NOTHING;
UPDATE deceased36 s SET mapped_burial_id=b.burial_id FROM public.burial_record b
WHERE s.mapped_burial_id IS NULL AND b.register_import_key=s.import_key;
INSERT INTO public.graves(lot_id,grave_label,status,burial_id,notes)
SELECT b.lot_id,'Register '||b.burial_id,'Occupied',b.burial_id,
  'Imported from Block 36 register. Individual grave position and dates not recorded.'
FROM public.burial_record b JOIN deceased36 s ON s.mapped_burial_id=b.burial_id
WHERE NOT EXISTS(SELECT 1 FROM public.graves g WHERE g.burial_id=b.burial_id);
UPDATE public.cemetery_lot l SET status=CASE
  WHEN EXISTS(SELECT 1 FROM public.burial_record b WHERE b.lot_id=l.lot_id) THEN 'Occupied'
  WHEN EXISTS(SELECT 1 FROM public.lot_ownership o WHERE o.lot_id=l.lot_id) THEN 'Reserved'
  ELSE l.status END
WHERE l.lot_id IN(SELECT lot_id FROM source36)
AND l.status IS DISTINCT FROM CASE
  WHEN EXISTS(SELECT 1 FROM public.burial_record b WHERE b.lot_id=l.lot_id) THEN 'Occupied'
  WHEN EXISTS(SELECT 1 FROM public.lot_ownership o WHERE o.lot_id=l.lot_id) THEN 'Reserved'
  ELSE l.status END;

DO $$ BEGIN
  IF EXISTS(SELECT 1 FROM deceased36 WHERE mapped_burial_id IS NULL)
    OR EXISTS(SELECT 1 FROM deceased36 s JOIN public.burial_record b ON b.burial_id=s.mapped_burial_id
      WHERE NOT EXISTS(SELECT 1 FROM public.graves g WHERE g.burial_id=b.burial_id AND g.lot_id=b.lot_id)) THEN
    RAISE EXCEPTION 'Burial/grave verification failed';
  END IF;
  IF EXISTS(SELECT 1 FROM source36 s WHERE s.owner_name IS NOT NULL AND NOT EXISTS(
    SELECT 1 FROM public.lot_ownership o JOIN owners36 r ON r.mapped_user_id=o.user_id
    WHERE o.lot_id=s.lot_id AND r.owner_key=upper(s.owner_name))) THEN
    RAISE EXCEPTION 'Owner/ownership verification failed';
  END IF;
END $$;
SELECT pg_notify('pgrst','reload schema');
SELECT transaction_timestamp() AS backup_run_id,
  (SELECT count(*) FROM owners36) AS owner_profiles,
  (SELECT count(*) FROM source36 WHERE owner_name IS NOT NULL) AS ownerships,
  (SELECT count(*) FROM deceased36) AS burials,
  (SELECT count(*) FROM public.graves g JOIN public.burial_record b USING(burial_id)
    JOIN deceased36 s ON s.mapped_burial_id=b.burial_id) AS graves;
COMMIT;
